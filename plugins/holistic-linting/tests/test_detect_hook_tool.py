"""Tests for pre-commit-compatible runner detection."""

from __future__ import annotations

from importlib.util import module_from_spec, spec_from_file_location
import shutil
import subprocess
import sys
from pathlib import Path

import pytest

SCRIPT = Path(__file__).parents[1] / "skills" / "holistic-linting" / "scripts" / "detect_hook_tool.py"
SPEC = spec_from_file_location("detect_hook_tool", SCRIPT)
assert SPEC
assert SPEC.loader
MODULE = module_from_spec(SPEC)
SPEC.loader.exec_module(MODULE)


def _repo(tmp_path: Path) -> Path:
    repo = tmp_path / "repo"
    repo.mkdir()
    subprocess.run(["git", "init", "-q", str(repo)], check=True)
    return repo


def _write_hook(repo: Path, content: str, hooks_path: str | None = None) -> Path:
    if hooks_path is not None:
        subprocess.run(["git", "-C", str(repo), "config", "core.hooksPath", hooks_path], check=True)
    result = subprocess.run(
        ["git", "-C", str(repo), "rev-parse", "--git-path", "hooks/pre-commit"],
        check=True,
        capture_output=True,
        text=True,
    )
    raw = result.stdout.removesuffix("\n")
    raw = raw.removesuffix("\r")
    hook = Path(raw)
    if not hook.is_absolute():
        hook = repo / hook
    hook.parent.mkdir(parents=True, exist_ok=True)
    hook.write_text(content, encoding="utf-8")
    return hook


def test_custom_hook_comment_is_not_framework_identity(tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> None:
    repo = _repo(tmp_path)
    _write_hook(repo, "#!/bin/sh\n# Custom pre-commit checks\nexit 0\n")
    monkeypatch.setattr(MODULE.shutil, "which", lambda name: f"/bin/{name}")
    assert MODULE.detect_tool(repo)[0] is None


def test_identified_missing_runner_is_not_substituted(tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> None:
    repo = _repo(tmp_path)
    _write_hook(repo, "#!/bin/sh\n# File generated by pre-commit: https://pre-commit.com\n")
    monkeypatch.setattr(MODULE.shutil, "which", lambda name: "/bin/prek" if name == "prek" else None)
    tool, error = MODULE.detect_tool(repo)
    assert tool == "pre-commit"
    assert error
    assert "unavailable" in error


def test_significant_hooks_path_whitespace_is_preserved(tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> None:
    repo = _repo(tmp_path)
    hook = _write_hook(repo, "#!/bin/sh\n# File generated by prek\n", hooks_path=" hooks")
    assert hook.parent.name == " hooks"
    monkeypatch.setattr(MODULE.shutil, "which", lambda name: f"/bin/{name}" if name == "prek" else None)
    assert MODULE.detect_tool(repo) == ("prek", None)


